async function project(t: { after(fn: () => Promise<void>): void }) {
    const root = await mkdtemp(path.join(os.tmpdir(), "backend-codegen-"))
    t.after(() => rm(root, { recursive: true, force: true }))
    await mkdir(path.join(root, "node_modules"))
    const location = fileURLToPath(new URL("../../../", import.meta.url))
    const sdk = location.endsWith(`${path.sep}.test-dist${path.sep}`) ? path.dirname(location.slice(0, -1)) : location
    await symlink(sdk, path.join(root, "node_modules/durable-actors"))
    await writeFile(path.join(root, "package.json"), JSON.stringify({ type: "module" }))
    return root
}

async function writeArtifacts(root: string, files: ReadonlyMap<string, string>) {
    for (const [file, content] of files) {
        await mkdir(path.dirname(path.join(root, file)), { recursive: true })
        await writeFile(path.join(root, file), content)
    }
}

async function checkUsageExamples(root: string, files: ReadonlyMap<string, string>) {
    const code = files.get("index.d.ts")!
    const examples = [...code.matchAll(/@example\n((?:[ \t]*\* .*\n)+)/g)].map(match =>
        match[1]!.replace(/^[ \t]*\* /gm, "").trim()
    )
    const [imports, ...snippets] = examples
    await writeArtifacts(path.join(root, "generated"), files)
    const consumer = path.join(root, "usage.ts")
    await writeFile(
        consumer,
        `${imports}\ndeclare const metadata: actors.Room.Metadata\n${snippets.map(example => `{\n${example}\n}`).join("\n")}`
    )
    checkTypes(consumer)
}

function checkTypes(entrypoint: string) {
    const program = ts.createProgram([entrypoint], {
        strict: true,
        noEmit: true,
        types: [],
        skipLibCheck: false,
        target: ts.ScriptTarget.ES2022,
        module: ts.ModuleKind.NodeNext
    })
    assert.deepEqual(
        ts
            .getPreEmitDiagnostics(program)
            .map(diagnostic => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")),
        []
    )
}
