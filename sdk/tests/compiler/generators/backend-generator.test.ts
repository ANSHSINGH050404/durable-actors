test("generates callable typed backend stubs in a consumer without actor source and with declared type dependencies", async t => {
    const author = await project(t)
    await mkdir(path.join(author, "node_modules/private-data"))
    await writeFile(
        path.join(author, "node_modules/private-data/package.json"),
        JSON.stringify({ name: "private-data", version: "1.0.0", types: "index.d.ts" })
    )
    await writeFile(
        path.join(author, "node_modules/private-data/index.d.ts"),
        "export interface Message { text: string; reply?: Message }"
    )
    const entrypoint = path.join(author, "actors.ts")
    await writeFile(
        entrypoint,
        `
        import { Actor } from "durable-actors"
        import type { Message } from "private-data"
        export class ChatRoom extends Actor<{}, never, never> {
            async sendMessage(input: Message): Promise<Message> { return input }
            async clear(): Promise<void> {}
            async count(scale = 1): Promise<number> { return scale }
            async tags(...tags: string[]): Promise<string[]> { return tags }
            async nullable(): Promise<null> { return null }
            private async secret() {}
        }
        throw new Error("must never execute")
    `
    )
    const contract = JSON.parse(JSON.stringify(new ActorCompiler().compileContract(entrypoint)))
    const dependency = await readFile(path.join(author, "node_modules/private-data/index.d.ts"), "utf8")
    await rm(author, { recursive: true, force: true })
    const files = await generateClientArtifacts(contract)
    assert.ok(files.has("index.d.ts"))
    const consumer = await project(t)
    await mkdir(path.join(consumer, "node_modules/private-data"))
    await writeFile(
        path.join(consumer, "node_modules/private-data/package.json"),
        JSON.stringify({ name: "private-data", version: "1.0.0", types: "index.d.ts" })
    )
    await writeFile(path.join(consumer, "node_modules/private-data/index.d.ts"), dependency)
    await writeArtifacts(consumer, files)
    await writeFile(
        path.join(consumer, "consumer.ts"),
        `
        import { actors } from "./index.js"
        const room = actors.ChatRoom.get("room-123")
        const grant: Promise<{ websocketUrl: string; homeRegion: string; connectByMs: number }> = actors.ChatRoom.prepareWebsocket({ actorId: "room-123", metadata: {} })
        const message: Promise<{ text: string; reply?: { text: string } }> = room.sendMessage({ text: "hi" })
        const cleared: Promise<void> = room.clear()
        const count: Promise<number> = room.count()
        const tags: Promise<string[]> = room.tags("one", "two")
        const nullable: Promise<null> = room.nullable()
        // @ts-expect-error wrong argument type
        room.sendMessage({ text: 123 })
        // @ts-expect-error required argument
        room.sendMessage()
        // @ts-expect-error private method
        room.secret()
        // @ts-expect-error recursive type
        room.sendMessage({ text: "hi", reply: { text: 123 } })
        // @ts-expect-error wrong result type
        const wrong: Promise<string> = room.count()
        // @ts-expect-error wrong rest type
        room.tags(123)
    `
    )
    checkTypes(path.join(consumer, "consumer.ts"))
    const outfile = path.join(consumer, "backend.mjs")
    const bundled = await build({
        entryPoints: [path.join(consumer, "index.js")],
        outfile,
        bundle: true,
        format: "esm",
        platform: "node",
        metafile: true
    })
    assert.equal(
        Object.keys(bundled.metafile!.inputs).some(file => file.includes("private-data")),
        false
    )
    const { actors } = await import(pathToFileURL(outfile).href)
    const calls: unknown[][] = []
    const room = actors.ChatRoom.get("room-123", {
        async invoke(...args: unknown[]) {
            calls.push(args)
            return args[2] === "sendMessage" ? { text: "hi" } : null
        }
    })
    assert.deepEqual(await room.sendMessage({ text: "hi" }), { text: "hi" })
    assert.equal(await room.clear(), undefined)
    assert.equal(await room.nullable(), null)
    assert.deepEqual(calls[0], ["ChatRoom", "room-123", "sendMessage", [{ text: "hi" }]])
    const browser = await build({
        entryPoints: [path.join(consumer, "index.js")],
        bundle: true,
        platform: "browser",
        format: "esm",
        write: false,
        metafile: true
    })
    assert.equal(
        Object.keys(browser.metafile!.inputs).some(file =>
            /\/(?:backend\.js|proxy\.js|client\/|@grpc\/|typescript\/|private-data\/)|node:/.test(file)
        ),
        false
    )
    const browserModule = await import(
        `data:text/javascript;base64,${Buffer.from(browser.outputFiles![0]!.text).toString("base64")}`
    )
    assert.throws(() => browserModule.actors.ChatRoom.get("room-123"), /server/)
    assert.throws(() => browserModule.actors.ChatRoom.prepareWebsocket({ actorId: "room-123", metadata: {} }), /server/)
    assert.throws(() => new browserModule.ActorProxy(), /server/)
})

