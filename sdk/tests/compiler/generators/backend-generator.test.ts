test("groups public state and method arguments and results under each actor", async t => {
    const root = await project(t)
    const entrypoint = path.join(root, "actors.ts")
    await writeFile(
        entrypoint,
        `
        import { Actor, Persisted, Emittable } from "durable-actors"
        type State = { id: number }
        type Methods = { label: string }
        type Parameters = { count: number }
        type ReturnType = { text: string }
        type Awaited = { done: boolean }
        export class ChatRoom extends Actor<{ userId: string }, string, never> {
            @Persisted @Emittable history: string[] = []
            @Persisted private secret = "hidden"
            async ClearHistoryKeepLast(keep: number, reason?: string): Promise<number> { return keep }
            async count(scale = 1) { return scale }
            async tags(...tags: string[]) { return tags }
            async clear(): Promise<void> {}
            async fail(): Promise<never> { throw new Error("failed") }
            async named(input: State): Promise<Methods> { return { label: String(input.id) } }
            async ["clear-history"]() { return 1 }
            async Methods() { return 1 }
            async utilityNames(input: Parameters, output: ReturnType): Promise<Awaited> { return { done: input.count > 0 } }
            private async hidden() {}
        }
    `
    )
    const files = await generateClientArtifacts(new ActorCompiler().compileContract(entrypoint))
    assert.ok(files.has("runtime/index.d.ts"))
    await writeArtifacts(root, files)
    await writeFile(
        path.join(root, "consumer.ts"),
        `
        import { actors } from "./index.js"
        type History = actors.ChatRoom.State["history"]
        type Args = actors.ChatRoom.Methods.ClearHistoryKeepLast.Args
        type Result = actors.ChatRoom.Methods.ClearHistoryKeepLast.Result
        const history: History = ["hello"]
        const state: actors.ChatRoom.State = { history }
        const args: Args = [2]
        const reason: Args = [2, "cleanup"]
        const result: Result = 2
        const called: Promise<Result> = actors.ChatRoom.get("lobby").ClearHistoryKeepLast(...args)
        const defaults: actors.ChatRoom.Methods.count.Args = []
        const tags: actors.ChatRoom.Methods.tags.Args = ["one", "two"]
        const cleared: actors.ChatRoom.Methods.clear.Result = undefined
        declare const failure: actors.ChatRoom.Methods.fail.Result
        const never: never = failure
        const input: actors.ChatRoom.Methods.named.Args = [{ id: 1 }]
        const output: actors.ChatRoom.Methods.named.Result = { label: "one" }
        const unusual: actors.ChatRoom.Methods["clear-history"]["Args"] = []
        const colliding: actors.ChatRoom.Methods.Methods.Result = 1
        const utilityArgs: actors.ChatRoom.Methods.utilityNames.Args = [{ count: 1 }, { text: "ok" }]
        const utilityResult: actors.ChatRoom.Methods.utilityNames.Result = { done: true }
        // @ts-expect-error arguments retain their types
        const wrong: Args = ["two"]
        // @ts-expect-error the first argument is required
        const missing: Args = []
        // @ts-expect-error Result is the resolved value
        const promise: Result = Promise.resolve(2)
        // @ts-expect-error private state is excluded
        type Secret = actors.ChatRoom.State["secret"]
        // @ts-expect-error private methods are excluded
        type Hidden = actors.ChatRoom.Methods.hidden.Args
    `
    )
    checkTypes(path.join(root, "consumer.ts"))
})

test("preserves named RPC types and their dependencies in clients generated from stored contracts", async t => {
    const author = await project(t)
    const entrypoint = path.join(author, "actors.ts")
    await writeFile(
        entrypoint,
        `
        import { Actor } from "durable-actors"
        interface Author { name: string }
        interface Message { text: string; author: Author; reply?: Message }
        type SendMessageInput = { text: string }
        export class ChatRoom extends Actor<{}, never, never> {
            async sendMessage(input: SendMessageInput): Promise<Message> {
                return { text: input.text, author: { name: "Ada" } }
            }
            async latest(): Promise<Message> { return this.sendMessage({ text: "hi" }) }
        }
    `
    )
    const contract = JSON.parse(JSON.stringify(new ActorCompiler().compileContract(entrypoint)))
    await rm(author, { recursive: true, force: true })
    const files = await generateClientArtifacts(contract)
    const code = files.get("types.d.ts")!
    assert.match(code, /(?:type|interface) SendMessageInput\b/)
    assert.match(code, /interface Message\b/)
    assert.match(code, /interface Author\b/)
    assert.match(code, /sendMessage\(input: SendMessageInput\): Promise<Message>/)
    assert.match(code, /latest\(\): Promise<Message>/)
    assert.match(code, /reply\?: Message/)
    const consumer = await project(t)
    await writeArtifacts(consumer, files)
    checkTypes(path.join(consumer, "index.d.ts"))
})

